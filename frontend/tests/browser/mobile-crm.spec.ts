import { expect, test } from '@playwright/test'
import { enter, incomingLead, mockAccess, noOverflow, screenshot, waitForListResults } from './crmFixtures'

test('mobile app: navigation preserves the filter, reading position and focus', async ({ page, context }, info) => {
  test.skip(info.project.name !== 'phone')
  const server = await mockAccess(context)
  server.leads = Array.from({ length: 20 }, (_, index) => incomingLead(20 - index))
  server.leads.push(incomingLead(21, [{ id: 2, name: 'Реклама', is_system: true }]))
  await page.goto('/')
  await expect(page.getByRole('navigation', { name: 'Управление CRM' })).toHaveCount(0)
  await enter(page, 'demo')
  await waitForListResults(page)
  const dock = page.getByRole('navigation', { name: 'Управление CRM' })
  await expect(dock).toBeVisible()
  await page.getByRole('combobox', { name: 'Направление', exact: true }).click()
  await page.getByText('Сайт', { exact: true }).last().click()
  const lead = server.leads[10]
  const row = page.locator(`[data-lead-id="${lead.id}"]:visible`)
  await row.scrollIntoViewIfNeeded()
  const top = await row.evaluate(element => element.getBoundingClientRect().top)
  await page.getByRole('button', { name: `Открыть карточку: ${lead.name}`, exact: true }).click()
  await expect(page.getByRole('region', { name: 'Карточка заявки' })).toBeVisible()
  await dock.getByRole('button', { name: 'Заявки', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Сбросить фильтр', exact: true })).toBeVisible()
  await expect(page.getByLabel('Всего заявок: 20', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Открыть карточку: Тест автообновления 21', exact: true })).toHaveCount(0)
  await expect.poll(async () => Math.abs(await row.evaluate(element => element.getBoundingClientRect().top) - top)).toBeLessThan(4)
  await expect(page.getByRole('button', { name: `Открыть карточку: ${lead.name}`, exact: true })).toBeFocused()
  await page.evaluate(() => window.scrollTo(0, document.documentElement.scrollHeight))
  const last = page.locator('[data-lead-id]:visible').last()
  await expect.poll(async () => {
    const card = await last.boundingBox()
    const panel = await dock.boundingBox()
    return !!card && !!panel && card.y + card.height <= panel.y
  }).toBe(true)
  await dock.getByRole('button', { name: 'Добавить заявку', exact: true }).click()
  await expect(page.getByLabel('Имя', { exact: true })).toBeVisible()
  await expect(dock).toHaveCount(0)
  await page.getByLabel('Имя', { exact: true }).fill('Тестовый черновик')
  await page.getByRole('button', { name: 'К списку заявок', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Выйти без сохранения?' })).toBeVisible()
  await page.getByRole('button', { name: 'Остаться', exact: true }).click()
  await expect(page.getByLabel('Имя', { exact: true })).toHaveValue('Тестовый черновик')
  await noOverflow(page)
})

